    private void txtBuscarProductosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtBuscarProductosActionPerformed
        String busqueda = txtBuscarProductos.getText().trim().toLowerCase();

        if (busqueda.isEmpty()) {
            cargarProductosEnTabla();
            return;
        }

        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tablaProductosDisponibles.getModel();
        modelo.setRowCount(0);

        for (Producto p : inventario.obtenerTodosLosProductos()) {
            if (p.getNombreProducto().toLowerCase().contains(busqueda)
                    || p.getCodigoProducto().toLowerCase().contains(busqueda)
                    || p.getCategoriaProducto().toLowerCase().contains(busqueda)) {

                Object[] fila = {
                    p.getCodigoProducto(),
                    p.getNombreProducto(),
                    p.getCategoriaProducto(),
                    String.format("₡%.2f", p.getPrecioProducto()),
                    p.getCantidadStock()
                };
                modelo.addRow(fila);
            }
        }
    }//GEN-LAST:event_txtBuscarProductosActionPerformed

    private void btnAgregarAlCarritoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarAlCarritoActionPerformed
        int filaSeleccionada = tablaProductosDisponibles.getSelectedRow();

        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un producto.");
            return;
        }

        String codigoProducto = tablaProductosDisponibles.getValueAt(filaSeleccionada, 0).toString();
        Producto producto = inventario.buscarProducto(codigoProducto);

        if (producto == null) {
            JOptionPane.showMessageDialog(this, "Producto no encontrado.");
            return;
        }

        int cantidadSolicitada = (int) spinnerCantidad.getValue();

        // Validar stock disponible
        int cantidadEnCarrito = obtenerCantidadEnCarrito(codigoProducto);
        int stockDisponible = producto.getCantidadStock() - cantidadEnCarrito;

        if (cantidadSolicitada > stockDisponible) {
            JOptionPane.showMessageDialog(
                    this,
                    "Stock insuficiente. Disponible: " + stockDisponible,
                    "Stock Insuficiente",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        // Verificar si el producto ya está en el carrito
        boolean encontrado = false;
        for (ItemCarrito item : carrito) {
            if (item.getProducto().getCodigoProducto().equals(codigoProducto)) {
                item.setCantidad(item.getCantidad() + cantidadSolicitada);
                encontrado = true;
                break;
            }
        }

        if (!encontrado) {
            carrito.add(new ItemCarrito(producto, cantidadSolicitada));
        }

        actualizarTablaCarrito();
        spinnerCantidad.setValue(1);
        JOptionPane.showMessageDialog(this, "Producto agregado al carrito.");
    }//GEN-LAST:event_btnAgregarAlCarritoActionPerformed

