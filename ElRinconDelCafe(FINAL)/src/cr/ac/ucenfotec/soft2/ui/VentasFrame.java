    /**
     * Cargar productos del inventario en la tabla
     */
    private void cargarProductosEnTabla() {
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tablaProductosDisponibles.getModel();
        modelo.setRowCount(0);

        for (Producto p : inventario.obtenerTodosLosProductos()) {
            Object[] fila = {
                p.getCodigoProducto(),
                p.getNombreProducto(),
                p.getCategoriaProducto(),
                String.format("₡%.2f", p.getPrecioProducto()),
                p.getCantidadStock()
            };
            modelo.addRow(fila);
        }
    }

    /**
     * Actualizar la tabla del carrito
     */
    private void actualizarTablaCarrito() {
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tablaCarrito.getModel();
        modelo.setRowCount(0);

        for (ItemCarrito item : carrito) {
            Object[] fila = {
                item.getProducto().getCodigoProducto(),
                item.getProducto().getNombreProducto(),
                item.getCantidad(),
                String.format("₡%.2f", item.getProducto().getPrecioProducto()),
                String.format("₡%.2f", item.getSubtotal())
            };
            modelo.addRow(fila);
        }

        actualizarTotales();
    }

    /**
     * Calcular y actualizar los totales
     */
    private void actualizarTotales() {
        double subtotal = 0;

        for (ItemCarrito item : carrito) {
            subtotal += item.getSubtotal();
        }

        double iva = subtotal * 0.13;
        double total = subtotal + iva;

        lblSubtotal.setText(String.format("₡%.2f", subtotal));
        lblIVA.setText(String.format("₡%.2f", iva));
        lblTotal.setText(String.format("₡%.2f", total));
    }

    /**
     * Limpiar venta y resetear formulario
     */
    private void limpiarVenta() {
        carrito.clear();
        clienteActual = null;
        txtCedulaCliente.setText("");
        lblNombreCliente.setText("");
        actualizarTablaCarrito();
        deshabilitarControlesVenta();
        spinnerCantidad.setValue(1);
        txtBuscarProductos.setText("");
    }

    /**
     * Obtener cantidad de un producto que ya está en el carrito
     */
    private int obtenerCantidadEnCarrito(String codigoProducto) {
        for (ItemCarrito item : carrito) {
            if (item.getProducto().getCodigoProducto().equals(codigoProducto)) {
                return item.getCantidad();
            }
        }
        return 0;
    }

