    private void btnModificarCantidadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarCantidadActionPerformed
        int filaSeleccionada = tablaCarrito.getSelectedRow();

        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un producto del carrito.");
            return;
        }

        ItemCarrito item = carrito.get(filaSeleccionada);

        String input = JOptionPane.showInputDialog(
                this,
                "Nueva cantidad (Stock disponible: " + item.getProducto().getCantidadStock() + "):",
                item.getCantidad()
        );

        if (input != null && !input.trim().isEmpty()) {
            try {
                int nuevaCantidad = Integer.parseInt(input.trim());

                if (nuevaCantidad <= 0) {
                    JOptionPane.showMessageDialog(this, "La cantidad debe ser mayor a 0.");
                    return;
                }

                if (nuevaCantidad > item.getProducto().getCantidadStock()) {
                    JOptionPane.showMessageDialog(
                            this,
                            "Stock insuficiente. Disponible: " + item.getProducto().getCantidadStock(),
                            "Stock Insuficiente",
                            JOptionPane.WARNING_MESSAGE
                    );
                    return;
                }

                item.setCantidad(nuevaCantidad);
                actualizarTablaCarrito();

            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Cantidad inválida.");
            }
        }
    }//GEN-LAST:event_btnModificarCantidadActionPerformed

    private void btnFinalizarVentaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFinalizarVentaActionPerformed
        if (carrito.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El carrito está vacío.");
            return;
        }

        if (clienteActual == null) {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un cliente.");
            return;
        }

        // Crear la venta
        String numeroVenta = gestorVentas.generarNumeroVenta();
        Venta venta = new Venta(numeroVenta, clienteActual, nombreUsuarioActual);

        // Agregar detalles
        for (ItemCarrito item : carrito) {
            venta.agregarDetalle(item.toDetalleVenta());
        }

        // Mostrar resumen
        int confirmacion = JOptionPane.showConfirmDialog(
                this,
                venta.obtenerResumen(),
                "Confirmar Venta",
                JOptionPane.YES_NO_OPTION
        );

        if (confirmacion == JOptionPane.YES_OPTION) {
            // Finalizar venta y generar factura
            Factura factura = venta.finalizarVenta();
            if (factura != null) {
                // Registrar venta y factura
                gestorVentas.registrarVenta(venta);
                gestorVentas.registrarFactura(factura);
                historial.agregarFactura(factura);

                // Mostrar factura
                JOptionPane.showMessageDialog(
                        this,
                        factura.generarFacturaTexto(),
                        "Factura Generada",
                        JOptionPane.INFORMATION_MESSAGE
                );

                // Limpiar todo para nueva venta
                limpiarVenta();
                cargarProductosEnTabla();
            } else {
                JOptionPane.showMessageDialog(
                        this,
                        "Error: Stock insuficiente para completar la venta.",
                        "Error",
                        JOptionPane.ERROR_MESSAGE
                );
            }
        }
    }//GEN-LAST:event_btnFinalizarVentaActionPerformed

